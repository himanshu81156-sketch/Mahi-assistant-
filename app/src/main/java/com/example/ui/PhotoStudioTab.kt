@Composable
fun PhotoStudioTab(
    selectedPhotoUri: String?,
    capturedBitmap: Bitmap?,
    onTakeCameraPhoto: () -> Unit,
    onPickGalleryPhoto: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var prompt by remember { mutableStateOf("") }
    var selectedStyle by remember { mutableStateOf("Realistic") }
    var selectedBg by remember { mutableStateOf("Cafe") }
    var selectedShirt by remember { mutableStateOf("Black") }
    var selectedSmile by remember { mutableStateOf("Thodi Smile") }
    var selectedFilter by remember { mutableStateOf("Normal") }
    var isGenerating by remember { mutableStateOf(false) }
    var hasGenerated by remember { mutableStateOf(false) }
    var statusMessage by remember { mutableStateOf<String?>(null) }

    var loadedBitmap by remember(selectedPhotoUri, capturedBitmap) {
        mutableStateOf(capturedBitmap)
    }

    LaunchedEffect(selectedPhotoUri) {
        if (selectedPhotoUri != null) {
            loadedBitmap = withContext(Dispatchers.IO) {
                runCatching {
                    context.contentResolver.openInputStream(Uri.parse(selectedPhotoUri))?.use {
                        BitmapFactory.decodeStream(it)
                    }
                }.getOrNull()
            }
        }
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 16.dp, vertical = 10.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .widthIn(max = 560.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp),
        ) {
            // A) PHOTO LO
            SectionTitle("A) Photo Lo")
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                Button(
                    onClick = onTakeCameraPhoto,
                    colors = ButtonDefaults.buttonColors(containerColor = MahiCyan, contentColor = MahiObsidian),
                    shape = RoundedCornerShape(14.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                        .testTag("camera_photo_button"),
                ) {
                    Icon(Icons.Rounded.CameraAlt, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.size(6.dp))
                    Text("Camera Se Photo Lo", maxLines = 1)
                }
                OutlinedButton(
                    onClick = onPickGalleryPhoto,
                    border = BorderStroke(1.dp, MahiMagenta),
                    shape = RoundedCornerShape(14.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                        .testTag("gallery_photo_button"),
                ) {
                    Icon(Icons.Rounded.PhotoLibrary, contentDescription = null, tint = MahiMagenta, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.size(6.dp))
                    Text("Gallery Se Photo Lo", color = MahiTextPrimary, maxLines = 1)
                }
            }

            // B) PHOTO BANAO (AI SE)
            SectionTitle("B) Photo Banao (AI Se)")
            OutlinedTextField(
                value = prompt,
                onValueChange = { prompt = it },
                placeholder = { Text("Mujhe cafe me black shirt me photo banao…", color = MahiTextSecondary) },
                minLines = 2,
                shape = RoundedCornerShape(16.dp),
                colors = OutlinedTextFieldDefaults.colors(
                    focusedBorderColor = MahiCyan,
                    unfocusedBorderColor = MahiOutline,
                    focusedContainerColor = MahiSurface,
                    unfocusedContainerColor = MahiSurface,
                    focusedTextColor = MahiTextPrimary,
                    unfocusedTextColor = MahiTextPrimary,
                ),
                modifier = Modifier.fillMaxWidth(),
            )

            ChipSelectorRow(
                label = "Style",
                options = listOf("Realistic", "Cartoon", "Cinematic", "8K"),
                selected = selectedStyle,
                accent = MahiCyan,
                onSelect = { selectedStyle = it },
            )

            Button(
                onClick = {
                    scope.launch {
                        isGenerating = true
                        statusMessage = null
                        delay(850L)
                        isGenerating = false
                        hasGenerated = true
                        statusMessage = "Demo Photo Ready ($selectedStyle) • Face same rakha gaya hai!"
                    }
                },
                enabled = !isGenerating,
                colors = ButtonDefaults.buttonColors(containerColor = MahiMagenta, contentColor = MahiObsidian),
                shape = RoundedCornerShape(14.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .height(50.dp),
            ) {
                if (isGenerating) {
                    CircularProgressIndicator(color = MahiObsidian, strokeWidth = 2.dp, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.size(8.dp))
                    Text(stringResource(R.string.loading_hindi))
                } else {
                    Icon(Icons.Rounded.AutoAwesome, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.size(8.dp))
                    Text("Photo Banao")
                }
            }

            // C) PHOTO EDIT KARO
            SectionTitle("C) Photo Edit Karo (Face Same Rahega)")
            ChipSelectorRow(
                label = "Background",
                options = listOf("Cafe", "School", "Beach", "City", "Mountain", "Room"),
                selected = selectedBg,
                accent = MahiCyan,
                onSelect = { selectedBg = it },
            )
            ChipSelectorRow(
                label = "Shirt",
                options = listOf("Black", "White", "Denim", "Check", "Yellow", "Red"),
                selected = selectedShirt,
                accent = MahiMagenta,
                onSelect = { selectedShirt = it },
            )
            ChipSelectorRow(
                label = "Smile",
                options = listOf("Thodi Smile", "Zyada Smile", "No Smile"),
                selected = selectedSmile,
                accent = MahiViolet,
                onSelect = { selectedSmile = it },
            )
            ChipSelectorRow(
                label = "Filter",
                options = listOf("Normal", "Warm", "Cool", "Black & White", "HDR", "Blur Background"),
                selected = selectedFilter,
                accent = MahiCyan,
                onSelect = { selectedFilter = it },
            )

            // LIVE PREVIEW CARD
            val colorFilter = remember(selectedFilter) {
                when (selectedFilter) {
                    "Black & White" -> ColorFilter.colorMatrix(ColorMatrix().apply { setToSaturation(0f) })
                    "Warm" -> ColorFilter.colorMatrix(
                        ColorMatrix(
                            floatArrayOf(
                                1.15f, 0f, 0f, 0f, 12f,
                                0f, 1.05f, 0f, 0f, 4f,
                                0f, 0f, 0.88f, 0f, 0f,
                                0f, 0f, 0f, 1f, 0f,
                            ),
                        ),
                    )
                    "Cool" -> ColorFilter.colorMatrix(
                        ColorMatrix(
                            floatArrayOf(
                                0.90f, 0f, 0f, 0f, 0f,
                                0f, 1.02f, 0f, 0f, 4f,
                                0f, 0f, 1.18f, 0f, 14f,
                                0f, 0f, 0f, 1f, 0f,
                            ),
                        ),
                    )
                    "HDR" -> ColorFilter.colorMatrix(
                        ColorMatrix(
                            floatArrayOf(
                                1.25f, 0f, 0f, 0f, -15f,
                                0f, 1.25f, 0f, 0f, -15f,
                                0f, 0f, 1.25f, 0f, -15f,
                                0f, 0f, 0f, 1f, 0f,
                            ),
                        ),
                    )
                    else -> null
                }
            }

            Surface(
                color = MahiSurface.copy(alpha = 0.92f),
                shape = RoundedCornerShape(22.dp),
                border = BorderStroke(
                    width = 1.dp,
                    brush = Brush.linearGradient(
                        listOf(MahiCyan.copy(alpha = 0.6f), MahiMagenta.copy(alpha = 0.5f)),
                    ),
                ),
                modifier = Modifier.fillMaxWidth(),
            ) {
                Column(modifier = Modifier.padding(12.dp)) {
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .aspectRatio(1f)
                            .clip(RoundedCornerShape(14.dp))
                            .background(MahiDeepNavy),
                    ) {
                        val bmp = loadedBitmap
                        if (bmp != null) {
                            Image(
                                bitmap = bmp.asImageBitmap(),
                                contentDescription = "Edited Photo Preview",
                                contentScale = ContentScale.Crop,
                                colorFilter = colorFilter,
                                modifier = Modifier.fillMaxSize(),
                            )
                        } else {
                            Canvas(modifier = Modifier.fillMaxSize()) {
                                drawRect(
                                    brush = Brush.linearGradient(
                                        colors = listOf(MahiDeepNavy, MahiViolet.copy(alpha = 0.4f), MahiCyan.copy(alpha = 0.3f)),
                                    ),
                                )
                                drawCircle(
                                    color = MahiCyan.copy(alpha = 0.25f),
                                    radius = size.minDimension * 0.28f,
                                    center = Offset(size.width / 2f, size.height / 2f),
                                )
                            }
                        }

                        Surface(
                            color = MahiObsidian.copy(alpha = 0.78f),
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier
                                .align(Alignment.BottomStart)
                                .padding(10.dp),
                        ) {
                            Text(
                                text = "$selectedStyle • BG: $selectedBg • Shirt: $selectedShirt • $selectedSmile",
                                style = MaterialTheme.typography.labelSmall,
                                color = MahiCyan,
                                modifier = Modifier.padding(horizontal = 10.dp, vertical = 6.dp),
                            )
                        }
                    }

                    statusMessage?.let { msg ->
                        Spacer(Modifier.height(8.dp))
                        Text(msg, style = MaterialTheme.typography.labelMedium, color = MahiCyan)
                    }
                }
            }

            // D) PHOTO SAVE / SHARE
            SectionTitle("D) Photo Save / Share")
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(8.dp),
            ) {
                Button(
                    onClick = {
                        scope.launch {
                            val saved = savePhotoToGallery(context, loadedBitmap, "MeraAI_${System.currentTimeMillis()}.png")
                            statusMessage = if (saved) {
                                "Photo Gallery me save ho gaya!"
                            } else {
                                "Photo save karne me dikkat aayi, dobara try karo."
                            }
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = MahiCyan, contentColor = MahiObsidian),
                    modifier = Modifier.weight(1f).height(48.dp),
                ) {
                    Icon(Icons.Rounded.Download, contentDescription = null, modifier = Modifier.size(16.dp))
                    Spacer(Modifier.size(4.dp))
                    Text("Save Gallery", maxLines = 1)
                }
                Button(
                    onClick = {
                        scope.launch {
                            val saved = savePhotoToGallery(context, loadedBitmap, "MeraAI_8K_${System.currentTimeMillis()}.png")
                            statusMessage = if (saved) {
                                "HD / 8K Photo download ho gaya!"
                            } else {
                                "Download karne me dikkat aayi."
                            }
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = MahiMagenta, contentColor = MahiObsidian),
                    modifier = Modifier.weight(1f).height(48.dp),
                ) {
                    Icon(Icons.Rounded.HighQuality, contentDescription = null, modifier = Modifier.size(16.dp))
                    Spacer(Modifier.size(4.dp))
                    Text("HD / 8K", maxLines = 1)
                }
                OutlinedButton(
                    onClick = {
                        val shareIntent = Intent(Intent.ACTION_SEND).apply {
                            type = "text/plain"
                            putExtra(
                                Intent.EXTRA_TEXT,
                                "Mera AI Assistant se banaya photo ($selectedStyle, $selectedBg, $selectedShirt shirt)!",
                            )
                        }
                        runCatching { context.startActivity(Intent.createChooser(shareIntent, "Share Photo")) }
                    },
                    border = BorderStroke(1.dp, MahiCyan),
                    modifier = Modifier.weight(1f).height(48.dp),
                ) {
                    Icon(Icons.Rounded.Share, contentDescription = null, tint = MahiCyan, modifier = Modifier.size(16.dp))
                    Spacer(Modifier.size(4.dp))
                    Text("Share", color = MahiTextPrimary, maxLines = 1)
                }
            }

            Spacer(Modifier.height(16.dp))
        }
    }
}

@Composable
fun SectionTitle(text: String) {
    Row(
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        Box(
            modifier = Modifier
                .size(width = 4.dp, height = 18.dp)
                .clip(RoundedCornerShape(50))
                .background(
                    Brush.verticalGradient(listOf(MahiCyan, MahiMagenta)),
                ),
        )
        Text(
            text = text,
            style = MaterialTheme.typography.titleMedium,
            color = MahiTextPrimary,
        )
    }
}

@Composable
fun ChipSelectorRow(
    label: String,
    options: List<String>,
    selected: String,
    accent: Color,
    onSelect: (String) -> Unit,
) {
    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
        Text(text = label, style = MaterialTheme.typography.labelMedium, color = MahiTextSecondary)
        Row(
            horizontalArrangement = Arrangement.spacedBy(8.dp),
            modifier = Modifier
                .fillMaxWidth()
                .horizontalScroll(rememberScrollState()),
        ) {
            options.forEach { opt ->
                val isSelected = opt == selected
                Surface(
                    color = if (isSelected) accent.copy(alpha = 0.2f) else MahiSurface,
                    shape = RoundedCornerShape(50),
                    border = BorderStroke(1.dp, if (isSelected) accent else MahiOutline),
                    modifier = Modifier
                        .minimumInteractiveComponentSize()
                        .clip(RoundedCornerShape(50))
                        .clickable { onSelect(opt) },
                ) {
                    Text(
                        text = opt,
                        style = MaterialTheme.typography.labelMedium,
                        color = if (isSelected) accent else MahiTextSecondary,
                        modifier = Modifier.padding(horizontal = 14.dp, vertical = 8.dp),
                    )
                }
            }
        }
    }
}

private suspend fun savePhotoToGallery(context: Context, source: Bitmap?, filename: String): Boolean =
    withContext(Dispatchers.IO) {
        runCatching {
            val bmp = source ?: Bitmap.createBitmap(1080, 1080, Bitmap.Config.ARGB_8888).apply {
                eraseColor(android.graphics.Color.rgb(15, 22, 41))
            }
            val values = ContentValues().apply {
                put(MediaStore.Images.Media.DISPLAY_NAME, filename)
                put(MediaStore.Images.Media.MIME_TYPE, "image/png")
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                    put(MediaStore.Images.Media.IS_PENDING, 1)
                }
            }
            val uri = context.contentResolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, values)
                ?: return@withContext false
            context.contentResolver.openOutputStream(uri)?.use { out ->
                bmp.compress(Bitmap.CompressFormat.PNG, 100, out)
            }
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                values.clear()
                values.put(MediaStore.Images.Media.IS_PENDING, 0)
                context.contentResolver.update(uri, values, null, null)
            }
            true
        }.getOrDefault(false)
    }
